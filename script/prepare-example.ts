import fs from "node:fs/promises";
const fields = "id,title,artist_title,artist_display,date_display,medium_display,dimensions,credit_line,main_reference_number,image_id,is_public_domain,provenance_text,thumbnail";
const response = await fetch(`https://api.artic.edu/api/v1/artworks/16568?fields=${fields}`, {signal:AbortSignal.timeout(20000)});
if (!response.ok) throw new Error(`Catalog unavailable: ${response.status}`);
const record = await response.json();
const d = record.data;
if (!d.is_public_domain || !d.image_id) throw new Error("Example image not approved for use");
const params = new URLSearchParams({action:"query",format:"json",titles:"File:Claude Monet - Water Lilies - 1933.1157 - Art Institute of Chicago.jpg",prop:"imageinfo",iiprop:"url|extmetadata",iiurlwidth:"1000"});
const commons = await (await fetch(`https://commons.wikimedia.org/w/api.php?${params}`)).json();
const info = (Object.values(commons.query.pages)[0] as any).imageinfo[0];
if(!info.extmetadata.Credit.value.includes("artic.edu/artworks/16568")||info.extmetadata.LicenseShortName.value!=="Public domain")throw new Error("Image identity or license mismatch");
const imageUrl = info.thumburl;
const image = await fetch(imageUrl,{signal:AbortSignal.timeout(20000)});
if (!image.ok) throw new Error("Image download failed");
await fs.mkdir("client/public/images",{recursive:true});
await fs.mkdir("fixtures",{recursive:true});
await fs.writeFile("client/public/images/water-lilies.jpg",Buffer.from(await image.arrayBuffer()));
await fs.writeFile("fixtures/monet.json",JSON.stringify({...record,retrievedAt:new Date().toISOString(),mirror:{url:info.thumburl,source:info.descriptionurl,license:"Public domain"}},null,2));
console.log(JSON.stringify({id:d.id,title:d.title,imageUrl,publicDomain:d.is_public_domain}));
